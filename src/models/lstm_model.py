"""LSTM Time-Series Comparison Model (DEV-009).

Source doc Section 15: "Used to model sequential patterns when the final
dataset contains enough observations per district/vehicle category; most
meaningful with monthly or another dense resolution. If only a small number
of yearly observations exist, treat LSTM results cautiously and possibly as
an experimental comparison only."

This module's `assess_sequence_density()` is the mandatory conditionality
check that must run - and be genuinely capable of returning "proceed" - before
any sequence is built, scaled, or trained (Business Rule). It is not a
hardcoded gate: it re-evaluates the real, current frozen dataset every run
against a documented threshold, so if a future session acquires monthly data,
rerunning this function is what would flip the decision, not a code change.

Decision rule (see REF-009 ADR-013 for the full reasoning):
- Section 15.1 explicitly describes the sequence window in MONTHS ("sliding
  window of previous 6 or 12 months"); it is written for monthly-cadence data,
  not yearly. If the dataset has no monthly observations at all, the
  documented construction is not applicable, independent of row count.
- Even granting the (undocumented, generous) reinterpretation of "6 or 12
  months" as "6 or 12 periods" using yearly data instead, at least
  `lstm.lookback_months` (configs/model_params.yaml, currently 6) + 1
  consecutive non-null periods are needed within a single series to form even
  one (input-window, target) training pair. This is checked too, and reported
  even when the monthly check alone is already decisive, so the shortfall is
  quantified rather than asserted.

This module intentionally does NOT contain sequence-construction, scaling, or
model-training code paths beyond what `assess_sequence_density()` needs,
because the current frozen dataset fails this gate (see
`reports/lstm_sequence_density_assessment.json`, generated by `run()`, and
DEV-009's Conditionality Check section) - per the Business Rule, a forced
sequence pipeline built on data this thin would not be a genuine "experimental
comparison," just a technically-present model with no real evidentiary value,
which the project's Hard Rules and DEV-009's own instructions rule out.
Sections 15.1/15.2/15.3 (sequence construction, model architecture, fair
comparison against XGBoost) are implemented ONLY once `assess_sequence_density()`
returns a "proceed" or "experimental" decision - see the module docstring's
re-evaluation note above.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

import pandas as pd
import yaml

from src.evaluation.experiment_tracking import MLRUNS_DIR as DEFAULT_MLRUNS_DIR, log_run

logger = logging.getLogger(__name__)

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIGS_DIR = REPO_ROOT / "configs"
PROCESSED_DIR = REPO_ROOT / "data" / "processed"
REPORTS_DIR = REPO_ROOT / "reports"

FROZEN_CSV = PROCESSED_DIR / "modelling_dataset_v1.csv"
MODEL_PARAMS_YAML = CONFIGS_DIR / "model_params.yaml"
ASSESSMENT_JSON = REPORTS_DIR / "lstm_sequence_density_assessment.json"

GROUP_KEYS = ["district", "vehicle_type"]

DECISION_PROCEED = "proceed"
DECISION_EXPERIMENTAL = "experimental"
DECISION_SKIP = "skip"


def _longest_consecutive_run(years: list[int]) -> int:
    """Longest run of consecutive integer years in a sorted, deduplicated
    list - e.g. [2019, 2020, 2022, 2023] -> 2 (either [2019,2020] or
    [2022,2023]), not 4."""
    if not years:
        return 0
    years = sorted(set(years))
    best = current = 1
    for i in range(1, len(years)):
        if years[i] == years[i - 1] + 1:
            current += 1
            best = max(best, current)
        else:
            current = 1
    return best


def assess_sequence_density(df: pd.DataFrame, min_lookback_periods: int) -> dict:
    """Computes the real sequence density of the frozen dataset and applies
    the documented conditionality rule (Section 15 / DEV-009). Returns a
    dict with the full evidence plus a `decision` in
    {"proceed", "experimental", "skip"} and a `reasoning` list explaining it -
    never a bare boolean, so the evidence is always auditable alongside the
    conclusion."""
    n_distinct_years = int(df["year"].nunique())
    month_populated = bool(df["month"].notna().any())

    # The sequence unit is a MONTH when monthly data exists (year*12+month,
    # so consecutive months stay consecutive integers across a year
    # boundary too), and a YEAR otherwise - using the bare `year` column as
    # the period for monthly data would collapse 12 same-year months into a
    # single distinct value and silently understate the real run length.
    if month_populated:
        period = df["year"] * 12 + df["month"]
    else:
        period = df["year"]
    df = df.assign(_period=period)

    observed = df["new_registrations"].notna() & df["_period"].notna()
    per_series_periods = (
        df[observed]
        .assign(_period=lambda d: d["_period"].astype(int))
        .groupby(GROUP_KEYS)["_period"]
        .apply(list)
    )
    n_series = df.groupby(GROUP_KEYS).ngroups
    longest_runs = per_series_periods.apply(_longest_consecutive_run)
    # Series with zero non-null observations don't appear in per_series_periods
    # at all (empty groupby result) - they have a run of 0, not "unknown".
    missing_series = n_series - len(longest_runs)
    all_runs = list(longest_runs.values) + [0] * missing_series

    max_consecutive_run = max(all_runs) if all_runs else 0
    required_run = min_lookback_periods + 1  # lookback window + 1 target period
    n_series_meeting_yearly_threshold = sum(1 for r in all_runs if r >= required_run)

    reasoning = []
    if not month_populated:
        decision = DECISION_SKIP
        reasoning.append(
            "Section 15.1's sequence window is defined in months ('sliding window of previous "
            "6 or 12 months'), written for monthly-cadence data. The frozen dataset's `month` "
            "column is null for every row (0% monthly coverage, yearly-only granularity per "
            "REF-001 Section 5) - the documented sequence construction does not apply at all, "
            "independent of row count."
        )
        reasoning.append(
            f"Even granting an undocumented reinterpretation of the window as {min_lookback_periods} "
            f"yearly periods instead of months, a series needs {required_run} consecutive non-null "
            f"yearly observations to form even one (input-window, target) training pair. The real "
            f"data's longest consecutive run across all {n_series} district x vehicle_type series is "
            f"{max_consecutive_run} year(s) (the dataset only spans 5 distinct years, 2019-2023, at "
            f"all); {n_series_meeting_yearly_threshold}/{n_series} series meet the "
            f"{required_run}-period threshold."
        )
    elif max_consecutive_run < required_run:
        decision = DECISION_SKIP
        reasoning.append(
            f"Monthly data exists, but the longest consecutive run ({max_consecutive_run} periods) "
            f"is still below the {required_run}-period minimum needed for a lookback-{min_lookback_periods} "
            f"sequence window."
        )
    elif n_series_meeting_yearly_threshold < n_series:
        decision = DECISION_EXPERIMENTAL
        reasoning.append(
            f"Only {n_series_meeting_yearly_threshold}/{n_series} series meet the {required_run}-period "
            "threshold - sequence modelling may proceed as an explicitly labelled experimental "
            "comparison restricted to that subset (Edge Case, DEV-009), not as a production model."
        )
    else:
        decision = DECISION_PROCEED
        reasoning.append(
            f"All {n_series} series meet the {required_run}-period threshold with genuine monthly "
            "granularity - sequence modelling may proceed per Section 15.1-15.3."
        )

    return {
        "n_distinct_years": n_distinct_years,
        "month_populated": month_populated,
        "n_series": int(n_series),
        "min_lookback_periods": int(min_lookback_periods),
        "required_consecutive_run": int(required_run),
        "max_consecutive_run": int(max_consecutive_run),
        "n_series_meeting_yearly_threshold": int(n_series_meeting_yearly_threshold),
        "decision": decision,
        "reasoning": reasoning,
    }


def run(
    frozen_csv: Path = FROZEN_CSV, model_params_path: Path = MODEL_PARAMS_YAML,
    assessment_json: Path = ASSESSMENT_JSON, mlruns_dir: Path = DEFAULT_MLRUNS_DIR,
) -> dict:
    logging.basicConfig(level=logging.INFO)

    df = pd.read_csv(frozen_csv)
    with open(model_params_path, encoding="utf-8") as f:
        model_params = yaml.safe_load(f)
    min_lookback_periods = model_params["lstm"]["lookback_months"]

    assessment = assess_sequence_density(df, min_lookback_periods)

    assessment_json.parent.mkdir(parents=True, exist_ok=True)
    with open(assessment_json, "w", encoding="utf-8") as f:
        json.dump(assessment, f, indent=2)

    logger.info("LSTM sequence-density assessment: decision=%s (%s)", assessment["decision"], assessment_json)
    if assessment["decision"] == DECISION_SKIP:
        logger.info(
            "LSTM is not built this run: %s. XGBoost (DEV-008) remains the production model "
            "(Section 23.5). See specs/development/DEV-009-lstm-model.md and REF-009 ADR-013.",
            " ".join(assessment["reasoning"]),
        )

    # Section 24 experiment tracking (DEV-014): the conditionality assessment
    # itself is logged as a run - documenting that LSTM was considered and
    # why it was (not) built is exactly the kind of thing Section 24 exists
    # to make auditable, not just a Boolean skip with no trail.
    log_run(
        run_name="lstm_conditionality_assessment",
        params={"min_lookback_periods": min_lookback_periods},
        metrics={
            "n_distinct_years": assessment["n_distinct_years"],
            "max_consecutive_run": assessment["max_consecutive_run"],
            "required_consecutive_run": assessment["required_consecutive_run"],
            "n_series_meeting_yearly_threshold": assessment["n_series_meeting_yearly_threshold"],
            "n_series": assessment["n_series"],
        },
        tags={"model_type": "lstm", "decision": assessment["decision"], "month_populated": str(assessment["month_populated"])},
        artifact_paths=[assessment_json],
        mlruns_dir=mlruns_dir,
    )

    return assessment


if __name__ == "__main__":
    run()
